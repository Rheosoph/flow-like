export function createHomeWidget(presetId: string): IHomeWidget {
	const item =
		HOME_WIDGET_PRESETS.find((entry) => entry.id === presetId) ??
		HOME_WIDGET_PRESETS[0];
	return {
		id: crypto.randomUUID(),
		type: item.type,
		title: item.name,
		description: "",
		size: { columns: item.columns, rows: item.rows },
		appearance: {
			variant: item.variant ?? "card",
			accent: item.accent ?? "neutral",
		},
		config: structuredClone(item.config),
	};
}

export function createDefaultHomeLayout(): IHomeLayout {
	const ids = [
		"greeting",
		"flowpilot-bar",
		"quick-actions",
		"recent-apps",
		"categories",
		"new-apps",
		"packages",
	];
	return {
		version: 1,
		widgets: ids.map((id) => ({
			...createHomeWidget(id),
			id: `default-${id}`,
		})),
	};
}

export function getHomeWidgetPreset(widget: IHomeWidget) {
	const candidates = HOME_WIDGET_PRESETS.filter(
		(item) => item.type === widget.type,
	);
	const key =
		widget.type === "data"
			? "visualization"
			: widget.type === "app-embed"
				? "target"
				: widget.type === "app-collection"
					? "source"
					: "mode";
	const matching = candidates.filter(
		(item) => item.config[key] === widget.config[key],
	);
	return (
		matching.find((item) => item.variant === widget.appearance.variant) ??
		matching[0] ??
		candidates[0]
	);
}
