/** Term → weight: 3 names the preset's job, 2 points at it, 1 hints at it. */
export type BotPresetVocabulary = Readonly<Record<string, number>>;

export interface BotPreset {
	/** Stored as the bot's `preset_id`; never rename one. */
	readonly id: string;
	readonly nameKey: string;
	readonly descriptionKey: string;
	readonly instructionsKey: string;
	/** Starter-pack characters and unpacked outfits only, so every account can save the look. */
	readonly appearance: BotAppearance;
	readonly capabilities: readonly BotCapability[];
	readonly location: BotLocation;
	readonly classification: IDataSensitivity;
	/** Words and synonyms people use for this job, matched without accents or case. */
	readonly keywords: {
		readonly en: BotPresetVocabulary;
		readonly de: BotPresetVocabulary;
	};
}

