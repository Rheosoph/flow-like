#[cfg(feature = "execute")]
use crate::document::openxml::write_zip;

use flow_like::flow::{
    execution::context::ExecutionContext,
    node::{Node, NodeLogic, NodeScores},
    pin::PinOptions,
    variable::VariableType,
};
use flow_like_catalog_core::FlowPath;
use flow_like_types::{async_trait, json::json};

#[crate::register_node]
#[derive(Default)]
pub struct PptxCreateNode;

impl PptxCreateNode {
    pub fn new() -> Self {
        Self
    }
}

#[async_trait]
impl NodeLogic for PptxCreateNode {
    fn get_node(&self) -> Node {
        let mut node = Node::new(
            "pptx_create",
            "Create PPTX",
            "Create a blank PPTX presentation with Flow Like brand theme (16:9, Calibri, #FF4343 accent).",
            "Document/PPTX",
        );
        node.add_icon("/flow/icons/file.svg");
        node.set_scores(
            NodeScores::new()
                .set_privacy(9)
                .set_security(8)
                .set_performance(7)
                .set_governance(8)
                .set_reliability(8)
                .set_cost(10)
                .build(),
        );

        node.add_input_pin("exec_in", "Input", "Trigger", VariableType::Execution);
        node.add_input_pin("output", "Output Path", "Save path", VariableType::Struct)
            .set_schema::<FlowPath>()
            .set_options(PinOptions::new().set_enforce_schema(true).build());

        node.add_output_pin("exec_out", "Done", "Continues", VariableType::Execution);
        node.add_output_pin("result", "Result", "Output file path", VariableType::Struct)
            .set_schema::<FlowPath>();

        node
    }

    #[cfg(feature = "execute")]
    async fn run(&self, context: &mut ExecutionContext) -> flow_like_types::Result<()> {
        context.deactivate_exec_pin("exec_out").await?;

        let output: FlowPath = context.evaluate_pin("output").await?;

        let mut files = std::collections::HashMap::new();

        files.insert(
            "[Content_Types].xml".to_string(),
            CONTENT_TYPES.as_bytes().to_vec(),
        );
        files.insert("_rels/.rels".to_string(), TOP_RELS.as_bytes().to_vec());
        files.insert(
            "ppt/presentation.xml".to_string(),
            PRESENTATION.as_bytes().to_vec(),
        );
        files.insert(
            "ppt/_rels/presentation.xml.rels".to_string(),
            PRESENTATION_RELS.as_bytes().to_vec(),
        );
        files.insert(
            "ppt/slideMasters/slideMaster1.xml".to_string(),
            SLIDE_MASTER.as_bytes().to_vec(),
        );
        files.insert(
            "ppt/slideMasters/_rels/slideMaster1.xml.rels".to_string(),
            SLIDE_MASTER_RELS.as_bytes().to_vec(),
        );
        files.insert(
            "ppt/slideLayouts/slideLayout1.xml".to_string(),
            SLIDE_LAYOUT.as_bytes().to_vec(),
        );
        files.insert(
            "ppt/slideLayouts/_rels/slideLayout1.xml.rels".to_string(),
            SLIDE_LAYOUT_RELS.as_bytes().to_vec(),
        );
        files.insert(
            "ppt/theme/theme1.xml".to_string(),
            THEME.as_bytes().to_vec(),
        );
        files.insert(
            "docProps/app.xml".to_string(),
            APP_XML.as_bytes().to_vec(),
        );
        files.insert(
            "docProps/core.xml".to_string(),
            CORE_XML.as_bytes().to_vec(),
        );

        let buf = write_zip(&files)?;
        output.put(context, buf, false).await?;
        context.set_pin_value("result", json!(output)).await?;
        context.activate_exec_pin("exec_out").await?;
        Ok(())
    }

    #[cfg(not(feature = "execute"))]
    async fn run(&self, _context: &mut ExecutionContext) -> flow_like_types::Result<()> {
        Err(flow_like_types::anyhow!("Requires the 'execute' feature"))
    }
}

